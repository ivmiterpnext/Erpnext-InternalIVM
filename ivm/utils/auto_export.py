"""Auto-export customizations when they change in the UI"""
import json
import os
import frappe
from frappe import scrub
from frappe.modules.utils import export_customizations
from ivm.utils.cleanup_custom_fields import cleanup_deleted_fields


def auto_export_custom_field(doc, method):
    """Auto-export Custom Field changes to custom/doctype.json"""
    # Skip if we're in install, migrate, sync, or import mode
    if (
        frappe.flags.in_install
        or frappe.flags.in_migrate
        or frappe.flags.in_import
        or frappe.flags.in_sync_customizations
    ):
        return

    # Skip if developer mode is not enabled
    if not frappe.conf.developer_mode:
        return

    # Get the doctype being customized
    doctype = doc.dt

    # Track deleted fields per doctype (for handling multiple deletions in one request)
    if method == "on_trash":
        if not hasattr(frappe.local, "deleted_custom_fields"):
            frappe.local.deleted_custom_fields = {}
        if doctype not in frappe.local.deleted_custom_fields:
            frappe.local.deleted_custom_fields[doctype] = set()
        frappe.local.deleted_custom_fields[doctype].add(doc.name)
    
    # For deletions, defer the export to after_commit so the database is updated
    if method == "on_trash":
        frappe.db.after_commit.add(lambda: _do_export_and_cleanup(doctype))
        return

    # For inserts and updates, export immediately  
    _do_export_and_cleanup(doctype)


def _do_export_and_cleanup(doctype):
    """Perform the actual export and cleanup operations"""
    # Debounce: Only export once per request per doctype
    if not hasattr(frappe.local, "auto_exported_doctypes"):
        frappe.local.auto_exported_doctypes = set()

    if doctype in frappe.local.auto_exported_doctypes:
        return

    frappe.local.auto_exported_doctypes.add(doctype)

    try:
        # Export customizations for this doctype
        export_customizations(
            module="IVM",
            doctype=doctype,
            sync_on_migrate=True,
            with_permissions=False
        )

        # Get all fields being deleted in this request (if any)
        deleted_fields = None
        if hasattr(frappe.local, "deleted_custom_fields") and doctype in frappe.local.deleted_custom_fields:
            deleted_fields = list(frappe.local.deleted_custom_fields[doctype])
        
        cleanup_deleted_fields(doctype, silent=True, exclude_fields=deleted_fields)

        # Add warning header to the exported file
        _add_warning_header(doctype)

        # Show a subtle toast notification instead of a dialog
        frappe.publish_realtime(
            "show_alert",
            {"message": f"Auto-exported customizations for {doctype}", "indicator": "green"},
            user=frappe.session.user
        )
    except Exception as e:
        frappe.log_error(f"Auto-export failed for {doctype}: {str(e)}", "Auto Export Error")



def _add_warning_header(doctype):
    """Add warning header to the exported custom JSON file"""
    try:
        # Get the path to the custom file
        module_name = "ivm"
        file_path = frappe.get_app_path("ivm", module_name, "custom", f"{scrub(doctype)}.json")
        
        if not os.path.exists(file_path):
            return
        
        # Read the existing JSON
        with open(file_path, "r") as f:
            data = json.load(f)
        
        # Add warning field at the beginning (if not already present)
        if "_WARNING" not in data:
            warning_data = {
                "_WARNING": "Do not edit this file manually. See README.md in this directory for instructions."
            }
            
            # Merge warning at the beginning
            new_data = {**warning_data, **data}
            
            # Write back with warning
            with open(file_path, "w") as f:
                json.dump(new_data, f, indent=1, sort_keys=False)
        else:
            # Warning already exists, no need to update
            pass
                
    except Exception as e:
        frappe.log_error(f"Failed to add warning header: {str(e)}", "Warning Header Error")
